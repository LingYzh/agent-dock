import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defaultHome, installationSettings, findAgy, findNpm, environmentReport } from '../plugin/environment.mjs';
import { agentEnvironment } from '../plugin/identity.mjs';
import { panelSync } from '../plugin/panel-sync.mjs';
import { mergePanelState } from '../plugin/panel-state.mjs';
import { projectEvents, recoveryMessage } from '../plugin/panel-view.mjs';
import { cacheHitRate } from '../plugin/usage.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
mkdirSync(path.join(root, '.qa'), { recursive: true });
const directory = mkdtempSync(path.join(root, '.qa', 'portable-'));
const profile = path.join(directory, 'fresh user');
const env = { USERPROFILE: profile, LOCALAPPDATA: path.join(profile, 'Local'), PATH: '' };
const defaultSettings = installationSettings(env);
assert.equal(defaultSettings.home, path.join(env.LOCALAPPDATA, 'AgentDock'));
assert.equal(defaultSettings.state, path.join(defaultSettings.home, 'state'));
assert.equal(findAgy(defaultSettings, env), undefined);
const custom = path.join(directory, 'custom & 空格');
mkdirSync(defaultHome(env), { recursive: true });
writeFileSync(path.join(defaultHome(env), 'installation.json'), JSON.stringify({ home: custom }));
assert.equal(installationSettings(env).home, custom);
assert.equal(installationSettings({ ...env, AGENT_DOCK_HOME: directory }).home, directory);
assert.equal(installationSettings(env, { home: profile }).home, profile);
mkdirSync(custom, { recursive: true });
writeFileSync(path.join(custom, 'settings.json'), JSON.stringify({ state: path.join(custom, 'data') }));
assert.equal(installationSettings(env).state, path.join(custom, 'data'));
assert.equal(installationSettings({ ...env, AGENT_DOCK_STATE_DIR: profile }).state, profile);
const fakeAgy = path.join(custom, 'agy.exe');
writeFileSync(fakeAgy, 'not executed');
assert.equal(findAgy({ agyBin: fakeAgy }, env), fakeAgy);
assert.equal(findAgy({}, { ...env, PATH: custom }), fakeAgy);
assert.equal(findAgy({ agyBin: path.join(custom, 'missing.exe') }, env), undefined);
assert.ok(environmentReport({ ...defaultSettings, agyBin: path.join(custom, 'missing.exe') }, env).errors.some(x => x.includes('AGY_BIN')));
assert.ok(findNpm(), 'Build environment must have npm');
const filtered = agentEnvironment({ PATH: 'test', ANTHROPIC_API_KEY: 'synthetic-test', CLAUDE_CONFIG_DIR: profile, CODEX_THREAD_ID: 'root', CODEX_API_KEY: 'synthetic-root', RANDOM_SECRET: 'synthetic-other' });
assert.equal(filtered.ANTHROPIC_API_KEY, 'synthetic-test');
assert.equal(filtered.CLAUDE_CONFIG_DIR, profile);
assert.equal(filtered.CODEX_API_KEY, undefined);
assert.equal(filtered.RANDOM_SECRET, undefined);

const events = Array.from({ length: 205 }, (_, index) => ({ seq: index + 1, method: 'session/update', params: { update: { sessionUpdate: 'agent_thought_chunk', content: { text: 'fixture thought\n' } } } }));
events.push({ seq: 206, method: 'bridge/turn_end', params: { stopReason: 'end_turn' } });
const record = { id: 'fixture', name: 'Portable test', status: 'completed', events };
const registry = new Map([[record.id, record]]);
const first = panelSync(registry, { id: record.id });
assert.equal(first.agent.hasMore, true);
assert.equal(projectEvents(first.agent.events, first.agent).some(x => x.type === 'thought' && x.streaming), false);
const second = panelSync(registry, { id: record.id, after: first.agent.cursor });
const merged = mergePanelState(first.agent, second.agent);
assert.deepEqual(merged.events, events);
assert.deepEqual(Object.keys(panelSync(registry, { id: record.id, after: merged.cursor, status: merged.status, revision: second.revision })), ['revision']);
assert.equal(recoveryMessage([{ seq: 207, method: 'bridge/recovered', params: {} }], 207), undefined);
assert.equal(cacheHitRate({ inputTokens: 20, cachedReadTokens: 80, cachedWriteTokens: 0 }), 80);
assert.equal(cacheHitRate({ inputTokens: 20, cachedReadTokens: 80 }), null);
const mcp = JSON.parse(readFileSync(path.join(root, 'plugin/mcp.json'), 'utf8'));
assert.deepEqual(mcp.mcpServers.agy_acp_probe.args, ['${PLUGIN_ROOT}/bootstrap.mjs']);
console.log(JSON.stringify({ passed: true, portablePaths: true, precedence: true, optionalProviders: true, credentialBoundary: true, syntheticPagedHistory: true }));
